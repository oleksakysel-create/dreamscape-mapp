/**
 * Generates supabase/seed.sql and public/coloring/*.svg from the TypeScript
 * domain data, so the database and the app share a single source of truth.
 * Usage: npm run seed:generate
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { COLORING_IMAGES, getIllustration, illustrationToSvg } from "../src/lib/coloring/illustrations";
import { ACHIEVEMENTS } from "../src/lib/data/achievements";
import { MONTHS } from "../src/lib/data/months";
import { LIFE_SPHERES } from "../src/lib/data/spheres";

const q = (v: string | number) => (typeof v === "number" ? String(v) : `'${v.replace(/'/g, "''")}'`);
const arr = (xs: readonly string[]) => `array[${xs.map(q).join(", ")}]::text[]`;
const values = (rows: (string | number)[][]) => rows.map((r) => `  (${r.join(", ")})`).join(",\n");

const root = join(__dirname, "..");
const svgDir = join(root, "public", "coloring");
mkdirSync(svgDir, { recursive: true });

const images = COLORING_IMAGES.map((m) => {
  const ill = getIllustration(m.id)!;
  writeFileSync(join(svgDir, `${m.id}.svg`), illustrationToSvg(ill));
  return { ...m, regions: ill.regions.length };
});

const sql = `-- AUTO-GENERATED by scripts/generate-seed.ts — do not edit by hand.
-- Seeds reference data: 12 life spheres, 12 months, ${MONTHS.reduce((n, m) => n + m.tasks.length, 0)} reflection tasks,
-- ${ACHIEVEMENTS.length} achievements and ${images.length} coloring illustrations.

insert into public.life_spheres (id, name, description, color, icon, sort_order) values
${values(LIFE_SPHERES.map((s) => [q(s.id), q(s.name), q(s.description), q(s.color), q(s.icon), s.sortOrder]))}
on conflict (id) do update set name = excluded.name, description = excluded.description,
  color = excluded.color, icon = excluded.icon, sort_order = excluded.sort_order;

insert into public.months (id, title, subtitle, description, action_prompt, gallery_categories) values
${values(MONTHS.map((m) => [m.id, q(m.title), q(m.subtitle), q(m.description), q(m.actionPrompt), arr(m.galleryCategories)]))}
on conflict (id) do update set title = excluded.title, subtitle = excluded.subtitle, description = excluded.description,
  action_prompt = excluded.action_prompt, gallery_categories = excluded.gallery_categories;

insert into public.reflection_tasks (id, month_id, prompt, hint, kind, sort_order) values
${values(MONTHS.flatMap((m) => m.tasks.map((t) => [q(t.id), t.month, q(t.prompt), q(t.hint), q(t.kind), t.sortOrder])))}
on conflict (id) do update set prompt = excluded.prompt, hint = excluded.hint, kind = excluded.kind, sort_order = excluded.sort_order;

insert into public.achievements (id, title, description, icon, category) values
${values(ACHIEVEMENTS.map((a) => [q(a.id), q(a.title), q(a.description), q(a.icon), q(a.category)]))}
on conflict (id) do update set title = excluded.title, description = excluded.description, icon = excluded.icon, category = excluded.category;

insert into public.coloring_images (id, title, category, difficulty, description, region_count, storage_path) values
${values(images.map((i) => [q(i.id), q(i.title), q(i.category), q(i.difficulty), q(i.description), i.regions, q(`coloring/${i.id}.svg`)]))}
on conflict (id) do update set title = excluded.title, category = excluded.category, difficulty = excluded.difficulty,
  description = excluded.description, region_count = excluded.region_count, storage_path = excluded.storage_path;
`;

writeFileSync(join(root, "supabase", "seed.sql"), sql);
console.log(`Wrote supabase/seed.sql and ${images.length} SVGs to public/coloring/`);
